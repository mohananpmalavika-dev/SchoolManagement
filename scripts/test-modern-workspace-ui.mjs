async function session(role = 'SCHOOL_ADMIN') {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
  await context.addInitScript(() => localStorage.setItem('accessToken', 'qa-access'));
  const rows = Array.from({ length: 13 }, (_, index) => ({ id: 's-' + index, name: 'Learner ' + (index + 1), firstName: 'Learner', lastName: String(index + 1), admissionNumber: 'ADM-' + (index + 1), dateOfBirth: '2016-04-12', gender: 'FEMALE', admissionDate: '2026-01-10', className: 'Grade 5', currentClassId: 'class-1', status: index >= 10 ? 'SUSPENDED' : 'ACTIVE' }));
  await context.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname.replace(/^\/api\/v1/, '/api');
    const method = route.request().method();
    const ok = data => route.fulfill({ json: { success: true, data } });
    if (method !== 'GET') writes.push({ path, method, body: route.request().postDataJSON() });
    if (path === '/api/auth/me') return ok({ id: 'user-' + role, firstName: 'Amara', lastName: 'Mwangi', email: 'qa@example.test', role, tenantId: 'tenant-1' });
    if (path === '/api/teacher-ai/options') return ok({ status: { configured: false } });
    if (path.endsWith('/overview')) return ok({ students: 13, staff: 6, classes: 2, balance: 125000, attendanceTotal: 13, attendanceRate: 92, weekly: Array.from({ length: 5 }, (_, index) => ({ date: '2026-10-0' + (5 + index), rate: 90 + index, total: index === 2 ? 0 : 13 })), events: [], activities: [] });
    if (path === '/api/workspace/students') return method === 'GET' ? ok(rows) : ok({ id: 'created', ...route.request().postDataJSON().data });
    if (path.startsWith('/api/workspace/students/') && method === 'PATCH') {
      const row = rows.find(item => item.id === path.split('/').at(-1));
      Object.assign(row, route.request().postDataJSON().data);
      row.name = row.firstName + ' ' + row.lastName;
      return ok(row);
    }
    if (path === '/api/workspace/classes') return ok([{ id: 'class-1', name: 'Grade 5' }]);
    if (path === '/api/workspace/guardians') return ok([]);
    if (path === '/api/workspace/users') return ok([]);
    return ok([]);
  });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  return { context, page };
}
